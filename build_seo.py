#!/usr/bin/env python3
"""Prepare deployable SEO files once the final public domain is known."""
import argparse, json, shutil
from pathlib import Path
from urllib.parse import urlparse
from html import escape
from xml.etree.ElementTree import Element, SubElement, ElementTree, indent

ROOT=Path(__file__).resolve().parent
HTMLS=sorted(ROOT.glob('*.html'))

def url_for(base, name):
    return base + ('/' if name=='index.html' else '/' + name)

def main():
    ap=argparse.ArgumentParser(description='Build publish/ with canonical, sitemap.xml and robots.txt')
    ap.add_argument('--domain', required=True, help='Final public root URL, e.g. https://example.ru or https://example.ru/blog')
    a=ap.parse_args()
    base=a.domain.strip().rstrip('/')
    parsed=urlparse(base)
    if parsed.scheme!='https' or not parsed.netloc or parsed.username or parsed.password or parsed.query or parsed.fragment or parsed.hostname in ('example.com','example.org','example.net','example.test','your-domain.example'):
        ap.error('Provide the real HTTPS website URL, without query/fragment.')
    dest=ROOT/'publish'
    if dest.exists(): shutil.rmtree(dest)
    dest.mkdir()
    for src in ROOT.iterdir():
        if src.is_file() and src.suffix in ('.html','.css','.svg','.js','.png','.jpg','.webp','.ico'):
            if src.suffix!='.html': shutil.copy2(src,dest/src.name); continue
            content=src.read_text(encoding='utf-8')
            u=url_for(base,src.name)
            # Generated SEO metadata is clearly delimited and only inserted once in output.
            injection=f'\n<!-- SEO: generated by build_seo.py -->\n<link rel="canonical" href="{escape(u,quote=True)}">\n<meta property="og:url" content="{escape(u,quote=True)}">\n'
            content=content.replace('</head>',injection+'</head>',1)
            # Enrich the existing JSON-LD object with its actual public URL.
            import re
            def enrich(m):
                obj=json.loads(m.group(2))
                if isinstance(obj,dict):
                    obj['url']=u
                    if obj.get('@type')=='Article': obj['mainEntityOfPage']={'@type':'WebPage','@id':u}
                return m.group(1)+json.dumps(obj,ensure_ascii=False,separators=(',',':'))+m.group(3)
            content=re.sub(r'(<script type="application/ld\+json" data-bytblock-seo>)(.*?)(</script>)',enrich,content,flags=re.S)
            (dest/src.name).write_text(content,encoding='utf-8')
    urlset=Element('urlset',xmlns='http://www.sitemaps.org/schemas/sitemap/0.9')
    for src in sorted(HTMLS,key=lambda x:(x.name!='index.html',x.name)):
        entry=SubElement(urlset,'url');SubElement(entry,'loc').text=url_for(base,src.name)
    indent(urlset)
    ElementTree(urlset).write(dest/'sitemap.xml',encoding='utf-8',xml_declaration=True)
    (dest/'robots.txt').write_text('User-agent: *\nAllow: /\n\nSitemap: '+base+'/sitemap.xml\n',encoding='utf-8')
    print(f'Generated {len(HTMLS)} pages, sitemap.xml and robots.txt in {dest}')

if __name__=='__main__': main()
